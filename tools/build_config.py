#!/usr/bin/env python3
"""Validate first-party rule sources and render their remote-resource entries."""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONFIG = ROOT / "Quantumult-X.conf"
REPOSITORY = "dmulle12/Quantumult-X"
BRANCH = "main"
UPDATE_INTERVAL = 172800
RULESETS = (
    ("proxy-services.list", "Project-Proxy", "proxy"),
    ("direct-cn.list", "Project-Direct-CN", "direct"),
)
BEGIN = "; BEGIN PROJECT REMOTE RULES (generated by tools/build_config.py; do not edit this block)"
END = "; END PROJECT REMOTE RULES"
DOMAIN_RE = re.compile(r"(?=.{1,253}$)(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}")


def read_rule_sets() -> list[tuple[str, str]]:
    collected: list[tuple[str, str]] = []
    seen: set[str] = set()
    for filename, _tag, required_policy in RULESETS:
        path = ROOT / "rulesets" / filename
        if not path.is_file():
            raise ValueError(f"missing ruleset: {path.relative_to(ROOT)}")
        active: list[tuple[int, str]] = []
        for number, raw in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
            line = raw.strip()
            if line and not line.startswith(("#", ";")):
                active.append((number, line))
        if not active:
            raise ValueError(f"no active rules found in {filename}")
        for position, (number, line) in enumerate(active):
            fields = [part.strip() for part in line.split(",")]
            if len(fields) != 3:
                raise ValueError(f"{filename}:{number}: expected a three-field Quantumult X rule")
            kind, value, policy = (field.lower() for field in fields)
            if policy != required_policy:
                raise ValueError(f"{filename}:{number}: expected policy {required_policy!r}, got {policy!r}")
            if kind == "host-suffix":
                if not DOMAIN_RE.fullmatch(value):
                    raise ValueError(f"{filename}:{number}: invalid DNS suffix {value!r}")
                if value in seen:
                    raise ValueError(f"{filename}:{number}: duplicate active suffix {value!r}")
                seen.add(value)
            elif kind == "geoip":
                if filename != "direct-cn.list" or value != "cn" or position != len(active) - 1:
                    raise ValueError(f"{filename}:{number}: only a final 'geoip, cn, direct' rule is allowed")
            else:
                raise ValueError(f"{filename}:{number}: unsupported rule type {kind!r}")
            collected.append((filename, line))
    if not any(line.lower().startswith("geoip, cn, direct") for filename, line in collected if filename == "direct-cn.list"):
        raise ValueError("direct-cn.list must end with 'geoip, cn, direct'")
    return collected


def render_block() -> str:
    lines = [BEGIN]
    for filename, tag, policy in RULESETS:
        url = f"https://raw.githubusercontent.com/{REPOSITORY}/{BRANCH}/rulesets/{filename}"
        lines.append(
            f"{url}, tag={tag}, force-policy={policy}, "
            f"update-interval={UPDATE_INTERVAL}, enabled=true"
        )
    lines.append(END)
    return "\n".join(lines)


def render_config(original: str) -> str:
    if original.count(BEGIN) != 1 or original.count(END) != 1:
        raise ValueError("Quantumult-X.conf must contain exactly one pair of remote-rule markers")
    start = original.index(BEGIN)
    finish = original.index(END)
    if finish < start:
        raise ValueError("remote-rule markers are in the wrong order")
    finish += len(END)
    return original[:start] + render_block() + original[finish:]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if Quantumult-X.conf is stale")
    args = parser.parse_args()
    try:
        rules = read_rule_sets()
        original = CONFIG.read_text(encoding="utf-8")
        generated = render_config(original)
    except (OSError, ValueError) as exc:
        print(f"Build failed: {exc}", file=sys.stderr)
        return 1
    if args.check:
        if original != generated:
            print("Quantumult-X.conf is out of date; run python3 tools/build_config.py", file=sys.stderr)
            return 1
        print(f"Remote resources are up to date ({len(RULESETS)} sets, {len(rules)} rules).")
        return 0
    CONFIG.write_text(generated, encoding="utf-8")
    print(f"Updated Quantumult-X.conf with {len(RULESETS)} remote sets ({len(rules)} source rules).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
