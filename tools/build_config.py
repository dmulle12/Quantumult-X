#!/usr/bin/env python3
"""Embed first-party rule-set sources into the importable Quantumult X profile."""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONFIG = ROOT / "Quantumult-X.conf"
RULESETS = ("proxy-services.list", "direct-cn.list")
BEGIN = "; BEGIN PROJECT RULES (generated by tools/build_config.py; do not edit this block)"
END = "; END PROJECT RULES"
DOMAIN_RE = re.compile(r"(?=.{1,253}$)(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}")
ALLOWED_POLICIES = {"proxy", "direct", "reject"}


def read_rule_sets() -> list[tuple[str, str]]:
    collected: list[tuple[str, str]] = []
    seen: set[str] = set()
    for filename in RULESETS:
        path = ROOT / "rulesets" / filename
        if not path.is_file():
            raise ValueError(f"missing ruleset: {path.relative_to(ROOT)}")
        for number, raw in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
            line = raw.strip()
            if not line or line.startswith(("#", ";")):
                continue
            fields = [part.strip() for part in line.split(",")]
            if len(fields) != 3 or fields[0] != "host-suffix":
                raise ValueError(f"{filename}:{number}: expected 'host-suffix, domain, policy'")
            domain, policy = fields[1].lower(), fields[2].lower()
            if not DOMAIN_RE.fullmatch(domain):
                raise ValueError(f"{filename}:{number}: invalid DNS suffix {domain!r}")
            if policy not in ALLOWED_POLICIES:
                raise ValueError(f"{filename}:{number}: unsupported policy {policy!r}")
            if domain in seen:
                raise ValueError(f"{filename}:{number}: duplicate active suffix {domain!r}")
            seen.add(domain)
            collected.append((filename, line))
    if not collected:
        raise ValueError("no active rules found")
    return collected


def render_block() -> str:
    lines = [BEGIN]
    current = None
    for filename, rule in read_rule_sets():
        if filename != current:
            if current is not None:
                lines.append("")
            lines.append(f"; Source: rulesets/{filename}")
            current = filename
        lines.append(rule)
    lines.append(END)
    return "\n".join(lines)


def render_config(original: str) -> str:
    if original.count(BEGIN) != 1 or original.count(END) != 1:
        raise ValueError("Quantumult-X.conf must contain exactly one pair of rule markers")
    start = original.index(BEGIN)
    finish = original.index(END)
    if finish < start:
        raise ValueError("rule markers are in the wrong order")
    finish += len(END)
    return original[:start] + render_block() + original[finish:]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if Quantumult-X.conf is stale")
    args = parser.parse_args()
    try:
        original = CONFIG.read_text(encoding="utf-8")
        generated = render_config(original)
    except (OSError, ValueError) as exc:
        print(f"Build failed: {exc}", file=sys.stderr)
        return 1
    if args.check:
        if original != generated:
            print("Quantumult-X.conf is out of date; run python3 tools/build_config.py", file=sys.stderr)
            return 1
        print("Generated profile is up to date.")
        return 0
    CONFIG.write_text(generated, encoding="utf-8")
    print(f"Updated Quantumult-X.conf from {len(read_rule_sets())} active first-party rules.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
